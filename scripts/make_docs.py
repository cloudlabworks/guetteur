"""Render docs/EVALUATION.md from eval/results.json + eval/runtime.json, and docs/TRACE_EXAMPLE.md from a fresh run.

    uv run python scripts/make_docs.py
"""

import json
from pathlib import Path

from guetteur.runner import run_scenario

ROOT = Path(__file__).resolve().parents[1]
res = json.loads((ROOT / "eval" / "results.json").read_text())
rt = json.loads((ROOT / "eval" / "runtime.json").read_text())
env = res["env"]
P = res["planners"]
names = {"rule": "Guetteur agent (rule planner)", "naive-guarded": "naive threshold + executor guardrails", "naive": "naive threshold, no agent, no guardrails"}

L = ["# Evaluation (SYNTHETIC scenes; generated by `guetteur eval` and `guetteur bench`)", "",
     "**Every number below is measured on synthetic OAK-D-style depth scenes with machine-readable ground truth. No physical camera and no AWS were used.**",
     "Thresholds were chosen while developing against this same scene family, so these figures are optimistic for real data (see DESIGN.md 9.3).", "",
     f"Environment: {env['cpu']}, {env['system']}, Python {env['python']}, OpenCV {env['opencv']} (pin `{env['opencv_pip_pin']}`), NumPy {env['numpy']}, "
     f"`cv2.getNumThreads()` = {env['cv2_threads']}, `cv2.useOptimized()` = {env['cv2_optimized']}, frames {env['frame']}, {env['cuda']}.", "",
     f"{res['seeds']} seeds x 11 scenarios = {P['rule']['runs']} runs per planner. Event-level scoring of approval *requests* against ground truth.", "",
     "## Headline", "",
     "| Planner | scenarios succeeded (all 11 / excl. documented miss) | true alerts | false alerts | misses | precision | recall (excl. documented miss) | median latency |",
     "| --- | --- | --- | --- | --- | --- | --- | --- |"]
for k in ("rule", "naive-guarded", "naive"):
    d = P[k]
    lat = f"{d['median_latency_frames']:.0f} frames ({d['latency_s_at_fps']:.1f} s at 5 fps)" if d["median_latency_frames"] is not None else "n/a"
    L.append(f"| {names[k]} | {d['scenario_success']}/{d['runs']} / {d['scenario_success_excl_known_miss']}/{d['n_excl_known_miss']} | {d['tp']} | {d['fp']} | {d['fn']} | "
             f"{d['precision']:.2f} | {d['recall']:.2f} ({d['recall_excl_known_miss']:.2f}) | {lat} |")
r = P["rule"]
L += ["", f"Receipts: {r['receipts_verified']['all_proven']}/{r['receipts_verified']['ledgers']} honest ledgers fully proven by the vendored prove-it-done verifier (`--min-instruments 2`).",
      f"Tamper tests (claim inflated / pointed at wrong pixels or time / re-pointed at another recording; `file:` hash recomputed by the attacker): "
      f"{r['tamper_rejected']['rejected']}/{r['tamper_rejected']['attempts']} rejected.",
      f"Planner calls: {r['planner_calls']} on {r['frames']} frames ({r['planner_call_rate']:.2f} per frame across all scenarios, which include long eventful stretches; "
      f"the `empty` control triggers {sum(x['counters']['planner_calls'] for x in r['rows'] if x['scenario'] == 'empty')} calls in {sum(x['counters']['frames'] for x in r['rows'] if x['scenario'] == 'empty')} frames).", "",
      "**Tolerance.** A claim passes if the re-measured value is within max(8 mm, 25% of the claimed value) (sensor: 0.08 coverage, drift: 0.01). Inflation beyond that is rejected; smaller inflation passes by design. The tamper test inflates by 2x, plus wrong place/time and wrong input.", "",
      "**Honest note on the tamper test.** The first run rejected 23/24. The miss was `lens_obstructed` with the *wrong place* tamper: the fault covers the whole frame, so relocating the claimed region leaves the claim true. "
      "That tamper is therefore defined as *wrong time* for sensor and drift claims (evidence window moved to the calibration period), and as *wrong pixels* for object claims; the table above is for the corrected definition.", "",
      "## Per scenario (seed 0 shown; all seeds in `eval/results.json`)", "",
      "| Scenario | agent | naive + guardrails | naive (raw) | agent alerts (frame, kind) |", "| --- | --- | --- | --- | --- |"]
def cell(d):
    if d["success"]:
        return "ok"
    bits = [f"false alerts {d['fp']}" if d["fp"] else "", f"missed {d['fn']}" if d["fn"] else "",
            "never " + "/".join(m.replace("min_", "") for m in d["behaviours_missing"]) if d["behaviours_missing"] else ""]
    return ", ".join(b for b in bits if b) + (" (documented)" if d["known_miss"] else "")
rows = {k: {(x["scenario"], x["seed"]): x for x in P[k]["rows"]} for k in P}
for sc in dict.fromkeys(x["scenario"] for x in P["rule"]["rows"]):
    a = rows["rule"][(sc, 0)]
    L.append(f"| `{sc}` | {cell(a)} | {cell(rows['naive-guarded'][(sc, 0)])} | {cell(rows['naive'][(sc, 0)])} | {', '.join(f'{f}:{k}' for f, k, z in a['alerts']) or 'none'} |")
L += ["", "Success means: every expected alert raised in its time window, no other alerts, and the required behaviours present (recheck / pause / drift compensation).",
      "`subthreshold_item_removed` is a **documented failure case**: a 10 mm change is about one filtered sigma and is invisible to every planner. We report it as a miss, not a pass.", ""]
L += ["## Runtime on this machine (CPU only)", "",
      f"Loop budget at {5} fps is 200 ms/frame. Measured over {rt['loop_frame_ms_2_zones']['n']} frames (2 zones each): "
      f"median **{rt['loop_frame_ms_2_zones']['median']} ms**, p95 {rt['loop_frame_ms_2_zones']['p95']} ms, p99 {rt['loop_frame_ms_2_zones']['p99']} ms per frame (perception + planner + executor, both zones). "
      f"Per zone-frame perception: median {rt['per_zone_frame_ms']['median']} ms, p95 {rt['per_zone_frame_ms']['p95']} ms. Planner call: median {rt['planner_call_ms']['median']} ms.", "",
      "| OpenCV 5 call (168x144 zone crop) | median ms | p95 ms |", "| --- | --- | --- |"]
for k, v in rt["stages"].items():
    L.append(f"| `{k}` | {v['median_ms']} | {v['p95_ms']} |")
L += ["", "These are the numbers to re-measure on Lambda arm64 (Graviton) after the first deploy; none have been measured there.", "",
      "## Known weaknesses (not hidden)", "",
      "* Sub-noise changes are invisible (above). Periodic integrated patrol checks would lift the floor; not built.",
      "* Synthetic noise is Gaussian and range-scaled; real stereo has structured errors (edges, reflective and dark surfaces, IR interference). Real clips are the first priority after this prototype.",
      "* Depth cannot say what an object is; claims are about regions becoming nearer or farther.",
      "* Latency is dominated by the persistence rule (10 frames = 2 s); a real deployment would use a longer hold to avoid nuisance alerts.",
      "* The two receipt checks are independent estimators over the same input; they cannot catch a wrong input that was pinned honestly. The digest only proves *which* input was checked.", ""]
(ROOT / "docs" / "EVALUATION.md").write_text("\n".join(L))

# ---- a trace example for the Agentic Vision evidence
out = ROOT / "runs"
run, meta = run_scenario("subtle_item_removed", 0, "rule", "approve", out_dir=out)
T = ["# Trace example: OpenCV 5 output changes the next tool call", "",
     "SYNTHETIC scene `subtle_item_removed`, seed 0. A low item (25 mm relief) is taken at frame 95. Steps where the planner acted (full trace: `runs/%s/trace.jsonl`)." % run.run, ""]
for e in run.trace:
    a, o = e["action"], e["observation"]
    b = o["blobs"][0] if o["blobs"] else {}
    T += [f"### frame {e['frame']}, zone `{e['zone']}`: `{a['kind']}` {json.dumps(a['args'])}", "",
          f"* OpenCV 5 observation: integrated frames = {o['integrated_n']}, blob contrast (mean |z|) = {b.get('snr')}, depth change = {b.get('dz_mm')} mm, persisted {o['persist']} frames, "
          f"valid depth {o['valid_frac']}, noise ratio {o['noise_ratio']}",
          f"* Why: {a['rationale']}", f"* Outcome: {e['outcome']}", ""]
T += ["Reading it: at the first step the evidence (contrast about 3.5) sits between 'ignore' and 'confident', so the planner chose `recheck_zone` with `n` computed from that number.",
      "The next perception call is an OpenCV 5 run on the *integrated* window; its contrast is higher, it persists, and only then does a human get asked. With the naive baseline the same scene produces no alert at all.", ""]
(ROOT / "docs" / "TRACE_EXAMPLE.md").write_text("\n".join(T))
print("wrote docs/EVALUATION.md, docs/TRACE_EXAMPLE.md")
